namespace Cheetah.Blazor.Components.Icons;

/// <summary>
/// Defines the available icon sets.
/// </summary>
public enum IconSet
{
    /// <summary>
    /// Bootstrap Icons - renders as &lt;i class="bi bi-{name}"&gt;
    /// </summary>
    Bootstrap,

    /// <summary>
    /// Material Symbols Outlined - renders as &lt;span class="material-symbols-outlined"&gt;
    /// </summary>
    Material,

    /// <summary>
    /// Material Symbols Rounded - renders as &lt;span class="material-symbols-rounded"&gt;
    /// </summary>
    MaterialRounded,

    /// <summary>
    /// Material Symbols Sharp - renders as &lt;span class="material-symbols-sharp"&gt;
    /// </summary>
    MaterialSharp
}
